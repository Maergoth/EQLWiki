<?php

namespace EQLImmersive;

/** Keep article navigation distinct from the wiki's action/revision URL variants. */
final class NavigationCrawl {

	private const ACTIONS = [
		'edit', 'submit', 'history', 'info', 'watch', 'unwatch', 'protect',
		'unprotect', 'delete', 'rollback', 'markpatrolled', 'purge', 'raw', 'render',
	];

	private const SPECIAL_PAGES = [
		'createaccount', 'userlogin', 'userlogout', 'whatlinkshere',
		'recentchangeslinked', 'recentchanges', 'upload', 'movepage', 'undelete',
		'block', 'unblock', 'changeemail', 'confirmemail', 'changepassword',
		'passwordreset', 'preferences', 'contributions', 'log', 'watchlist',
		'emailuser', 'userrights',
	];

	/** Decorate flat menu items, including native nested feed/action groups. */
	public static function applyToItems( array &$items ): void {
		foreach ( $items as &$item ) {
			if ( !is_array( $item ) ) {
				continue;
			}
			$item = self::decorate( $item );
			if ( isset( $item['links'] ) && is_array( $item['links'] ) ) {
				self::applyToItems( $item['links'] );
			}
		}
		unset( $item );
	}

	/** Apply the same policy before the skin clones its action overflow. */
	public static function applyToGroups( array &$groups ): void {
		// Personal tools have a separate native conversion that intentionally
		// accepts only a fixed property list. Leave account/notification menus
		// intact instead of promising relations that conversion would discard.
		foreach ( [ 'views', 'views-overflow', 'actions' ] as $key ) {
			if ( isset( $groups[$key] ) && is_array( $groups[$key] ) ) {
				self::applyToItems( $groups[$key] );
			}
		}
	}

	public static function decorate( array $item ): array {
		$href = $item['href'] ?? null;
		if ( !is_string( $href ) || !self::isUtilityUrl( $href ) ) {
			return $item;
		}
		$rel = $item['rel'] ?? '';
		if ( !is_string( $rel ) ) {
			return $item;
		}
		if ( !preg_match( '/(?:^|\s)nofollow(?:\s|$)/i', $rel ) ) {
			$item['rel'] = trim( $rel . ' nofollow' );
		}
		return $item;
	}

	/**
	 * Only classify local URLs generated by wiki navigation. External and
	 * protocol-relative destinations are deliberately outside this policy.
	 */
	private static function isUtilityUrl( string $href ): bool {
		if ( $href === '' || !in_array( $href[0], [ '/', '?' ], true ) ||
			str_starts_with( $href, '//' )
		) {
			return false;
		}
		$parts = parse_url( $href );
		if ( $parts === false || isset( $parts['host'] ) || isset( $parts['scheme'] ) ) {
			return false;
		}
		parse_str( $parts['query'] ?? '', $query );
		foreach ( [ 'oldid', 'diff', 'printable' ] as $key ) {
			if ( array_key_exists( $key, $query ) ) {
				return true;
			}
		}
		$action = $query['action'] ?? '';
		if ( is_string( $action ) && in_array( strtolower( $action ), self::ACTIONS, true ) ) {
			return true;
		}
		$veAction = $query['veaction'] ?? '';
		if ( is_string( $veAction ) && in_array( strtolower( $veAction ), [ 'edit', 'editsource' ], true ) ) {
			return true;
		}
		$title = $query['title'] ?? null;
		if ( $title === null ) {
			$path = rawurldecode( $parts['path'] ?? '' );
			if ( !preg_match( '~^/(?:wiki/)?(Special:[^/]+)(?:/|$)~i', $path, $match ) ) {
				return false;
			}
			$title = $match[1];
		}
		if ( !is_string( $title ) ||
			!preg_match( '~^Special:([^/]+)(?:/|$)~i', $title, $match )
		) {
			return false;
		}
		$specialName = strtolower( str_replace( [ ' ', '_' ], '', $match[1] ) );
		return in_array( $specialName, self::SPECIAL_PAGES, true );
	}
}
